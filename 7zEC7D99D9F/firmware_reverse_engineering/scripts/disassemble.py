#!/usr/bin/env python3
"""Produce annotated full disassembly.

Usage:
    python3 disassemble.py <dump.bin> [--out ../disassembly/full_disassembly.asm]
    python3 disassemble.py <dump.bin> --func 0x0801D074        # print one function to stdout
"""
import sys, os, re, argparse, json
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import analyze, dataflow
from thumb2 import decode_at

try:
    from annotations import FUNC_NAMES
except Exception:
    FUNC_NAMES = {}


def fname(addr):
    n = FUNC_NAMES.get(addr)
    return n[0] if n else 'sub_%08X' % addr


def string_at(fw, a, maxlen=60):
    o = a - fw.base
    if not (0 <= o < len(fw.d)): return None
    s = bytearray()
    while o < len(fw.d) and len(s) < maxlen and 0x20 <= fw.d[o] < 0x7F or (o < len(fw.d) and fw.d[o] in (10, 13, 9) and len(s) < maxlen):
        s.append(fw.d[o]); o += 1
    if len(s) >= 3 and (o >= len(fw.d) or fw.d[o] == 0):
        return s.decode('ascii', 'replace')
    return None


def annotate_value(fw, v, strings):
    if v is None: return ''
    if fw.in_flash(v & ~1):
        e = v & ~1
        if (v & 1) and e in fw.funcs: return '=%s' % fname(e)
        s = string_at(fw, v)
        if s: return '="%s"' % s.replace('\n', '\\n')
        return '=flash'
    c = dataflow.classify(v)
    if c: return '=%s.%s' % (c[0], c[1])
    if 0x20000000 <= v < 0x20010000: return '=ram_%08X' % v
    return ''


def format_function(fw, flows, e):
    r = fw.funcs[e]
    out = []
    callers = sorted({a for a, x in fw.funcs.items() if x['ok'] and e in list(x['calls'].values()) + list(x['tails'].values())})
    out.append('; ---- %s  @0x%08X  src=%s  callers=%s' % (fname(e), e, fw.entries.get(e), ' '.join('%08X' % c for c in callers[:8])))
    ins = sorted(r['insns'].items())
    labels = {I.target for _, I in ins if I.target is not None and I.kind in ('jump', 'cjump')}
    for t in r['tables'].values(): labels.update(t['targets'])
    for a, I in ins:
        if a in labels and a != e: out.append('loc_%08X:' % a)
        ann = ''
        if I.lit is not None and I.litsize:
            v = fw.u32(I.lit) if I.litsize == 4 else (fw.u16(I.lit) if I.litsize == 2 else fw.d[I.lit - fw.base])
            ann = '; [0x%08X]=0x%X %s' % (I.lit, v if v is not None else 0, annotate_value(fw, v, None))
        elif I.kind == 'call':
            ann = '; ' + fname(I.target)
        elif I.target is not None and I.kind in ('jump', 'cjump'):
            ann = '; loc_%08X' % I.target if I.target in r['insns'] else ('; -> ' + fname(I.target))
        hw = ('%04X' % I.raw) if I.size == 2 else ('%04X %04X' % (I.raw >> 16, I.raw & 0xFFFF))
        out.append('  %08X: %-9s %-34s %s' % (a, hw, I.text, ann))
    return '\n'.join(out)


def write_full(fw, flows, path):
    cov = {}
    owner = {}
    for e, r in fw.funcs.items():
        if not r['ok']: continue
        for a, I in r['insns'].items():
            if a not in cov: cov[a] = I; owner[a] = e
    lit = {}
    for e, r in fw.funcs.items():
        for a, I in r['lits'].items():
            if I.litsize:
                lit.setdefault(I.lit, []).append(a)
    jt = {}
    for r in fw.funcs.values():
        for a, t in r['tables'].items(): jt[t['table']] = t
    lbl = set()
    for I in cov.values():
        if I.target is not None and I.kind in ('jump', 'cjump'): lbl.add(I.target)
    for t in jt.values(): lbl.update(t['targets'])
    entries = set(fw.funcs)
    L = []
    L.append('; Annotated disassembly of %d bytes, base 0x%08X (generated by disassemble.py)' % (len(fw.d), fw.base))
    L.append('; Legend: instructions are Thumb/Thumb-2; "; [lit]=value" shows the resolved PC-relative literal.')
    a = fw.base
    end = fw.end
    # last non-FF
    last = len(fw.d)
    while last > 0 and fw.d[last - 1] == 0xFF: last -= 1
    last = (last + 15) & ~15
    litdone = set()
    while a < fw.base + last:
        if a in cov:
            I = cov[a]
            if a in entries:
                L.append('')
                r = fw.funcs[a]
                callers = sorted({x for x, y in fw.funcs.items() if y['ok'] and a in list(y['calls'].values()) + list(y['tails'].values())})
                L.append('; ==== %s  @0x%08X  (src: %s)  callers: %s' % (fname(a), a, fw.entries[a], ' '.join('%08X' % c for c in callers[:10])))
                nm = FUNC_NAMES.get(a)
                if nm: L.append('; %s [%s]' % (nm[1], nm[2]))
            if a in lbl and a not in entries: L.append('loc_%08X:' % a)
            ann = ''
            if I.lit is not None and I.litsize:
                v = fw.u32(I.lit) if I.litsize == 4 else (fw.u16(I.lit) if I.litsize == 2 else fw.d[I.lit - fw.base])
                ann = '; [0x%08X]=0x%X %s' % (I.lit, v or 0, annotate_value(fw, v, None))
            elif I.kind == 'call': ann = '; ' + fname(I.target)
            elif I.target is not None and I.kind in ('jump', 'cjump'):
                ann = '; loc_%08X' % I.target if I.target in lbl else ''
            hw = ('%04X' % I.raw) if I.size == 2 else ('%04X %04X' % (I.raw >> 16, I.raw & 0xFFFF))
            L.append('  %08X: %-9s %-34s %s' % (a, hw, I.text, ann))
            a += I.size; continue
        # literal / jump-table / data
        if a in lit:
            sz = 4
            for x in lit[a]:
                if fw.funcs  and True: pass
            v = fw.u32(a)
            ann = annotate_value(fw, v, None)
            L.append('  %08X: .word 0x%08X  %s ; lit-ref by %s' % (a, v, ann, ','.join('%08X' % x for x in lit[a][:4])))
            a += 4; continue
        if a in jt:
            t = jt[a]
            L.append('  %08X: ; jump table (%s x%d) -> %s' % (a, 'tbb' if t['entry_size'] == 1 else 'tbh', t['entries'],
                                                             ' '.join('%08X' % x for x in t['targets'])))
            a += t['entries'] * t['entry_size']
            if a & 1: a += 1
            continue
        # raw data run until next code/literal address
        b = a
        while b < fw.base + last and b not in cov and b not in lit and b not in jt and b - a < 16: b += 1
        chunk = fw.d[a - fw.base:b - fw.base]
        txt = ''.join(chr(c) if 0x20 <= c < 0x7F else '.' for c in chunk)
        L.append('  %08X: .byte %-48s ; |%s|' % (a, ' '.join('%02X' % c for c in chunk), txt))
        a = b
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    open(path, 'w').write('\n'.join(L) + '\n')
    return len(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('dump')
    ap.add_argument('--out', default=os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'disassembly', 'full_disassembly.asm'))
    ap.add_argument('--func', default=None)
    ap.add_argument('--base', default='0x08000000')
    a = ap.parse_args()
    fw = analyze.build(a.dump, int(a.base, 0), verbose=False)
    flows = dataflow.analyze_all(fw)
    if a.func:
        e = int(a.func, 0) & ~1
        print(format_function(fw, flows, e))
        return
    n = write_full(fw, flows, a.out)
    print('wrote', a.out, n, 'lines')


if __name__ == '__main__':
    main()
